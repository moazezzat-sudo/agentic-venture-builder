# --------------------------------------------------------------------------- HTML checks

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
OPTIONAL_CLOSE = {"p", "li", "td", "tr", "th", "option", "dt", "dd", "thead", "tbody", "tfoot", "head", "body", "html"}
EXTERNAL = re.compile(r"^\s*(https?:)?//", re.I)
SENDS_DATA = re.compile(r"\b(fetch|XMLHttpRequest|WebSocket|sendBeacon|EventSource)\b|\bimport\s*\(", re.I)


class _Checker(HTMLParser):
    """Collects visible text and structural problems; html.parser itself is lenient."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.stack: list[str] = []
        self.problems: list[str] = []
        self.text: list[str] = []
        self.scripts: list[str] = []
        self._skip = 0  # inside <script> or <style>
        self.tags: set[str] = set()

    def handle_starttag(self, tag: str, attrs: list[tuple[str, Optional[str]]]) -> None:
        self.tags.add(tag)
        a = {k.lower(): (v or "") for k, v in attrs}
        if tag == "script" and a.get("src"):
            self.problems.append(f"external script: {a['src'][:80]}")
        if tag in ("link", "iframe", "embed", "object") and (EXTERNAL.match(a.get("href", "")) or EXTERNAL.match(a.get("src", "") or a.get("data", ""))):
            self.problems.append(f"loads an external resource: <{tag}>")
        if tag in ("img", "audio", "video", "source") and EXTERNAL.match(a.get("src", "")):
            self.problems.append(f"loads an external resource: <{tag} src>")
        if tag == "form" and a.get("action", "#").strip() not in ("", "#"):
            self.problems.append(f"form sends data to {a['action'][:80]}")
        if tag in ("script", "style"):
            self._skip += 1
        if tag not in VOID:
            self.stack.append(tag)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, Optional[str]]]) -> None:
        self.handle_starttag(tag, attrs)
        if tag not in VOID and self.stack and self.stack[-1] == tag:
            self.stack.pop()
            if tag in ("script", "style"):
                self._skip -= 1

    def handle_endtag(self, tag: str) -> None:
        if tag in VOID:
            return
        if tag in ("script", "style") and self._skip:
            self._skip -= 1
        if tag not in self.stack:
            self.problems.append(f"closing </{tag}> without an opening tag")
            return
        while self.stack:
            top = self.stack.pop()
            if top == tag:
                break
            if top not in OPTIONAL_CLOSE:
                self.problems.append(f"<{top}> is not closed before </{tag}>")

    def handle_data(self, data: str) -> None:
        if self._skip:
            self.scripts.append(data)
        elif data.strip():
            self.text.append(data.strip())


def inspect_html(source: str) -> tuple[list[str], str]:
    """(problems, visible text) for an HTML document."""
    checker = _Checker()
    try:
        checker.feed(source)
        checker.close()
    except Exception as exc:  # html.parser rarely raises, but a crash is a failure, not a pass
        return [f"HTML does not parse: {type(exc).__name__}: {exc}"], ""
    problems = list(checker.problems)
    problems += [f"<{t}> is never closed" for t in checker.stack if t not in OPTIONAL_CLOSE]
    for required in ("html", "head", "title", "body"):
        if required not in checker.tags:
            problems.append(f"missing <{required}>")
    if any(SENDS_DATA.search(s) for s in checker.scripts):
        problems.append("script sends or loads data (fetch, XMLHttpRequest, WebSocket, sendBeacon or import)")
    return problems, "\n".join(checker.text)


def check_build(files: dict[str, Path]) -> tuple[list[str], list[dict[str, Any]]]:
    """Plain-Python checks before Gate 3. Returns (failures, guardrail violations)."""
    import agents._common as common

    failures: list[str] = []
    texts: dict[str, str] = {}
    for label, path in files.items():
        if path is None or not Path(path).exists():
            failures.append(f"{label}: file is missing")
            continue
        source = Path(path).read_text(encoding="utf-8")
        source = re.sub(r"^> \*\*(STUBBED|MOCKED)\*\*:[^\n]*\n+", "", source)  # the status label isn't content
        if not source.strip():
            failures.append(f"{label}: file is empty")
            continue
        if Path(path).suffix == ".html":
            problems, visible = inspect_html(source)
            failures += [f"{label}: {p}" for p in problems]
            texts[label] = visible
            if label == "landing" and DEMO_FORM_NOTICE not in visible:
                failures.append(f"landing: the notice \"{DEMO_FORM_NOTICE}\" is missing")
        else:
            texts[label] = source
    violations = common.text_violations(texts, rewritable=True, round_no=0)
    failures += [f"{v['source']}: guardrail {v['rule']}: \"{v['excerpt']}\"" for v in violations]
    return failures, violations


# --------------------------------------------------------------------------- building


def _drafts(state: dict[str, Any]) -> dict[str, Any]:
    return state.get("drafts") or {}


def landing_html(state: dict[str, Any]) -> tuple[str, str]:
    """(html, where the copy came from). Built from the Phase 2 copy; nothing is invented."""
    lp = (_drafts(state).get("phase2_lean_canvas") or {}).get("landing_page") or {}
    idea = str((state.get("brief") or {}).get("idea", "")).strip()
    if lp.get("headline"):
        source = "Phase 2 landing-page copy"
        headline, sub = lp["headline"], lp.get("subheadline", "")
        bullets, cta = lp.get("bullets") or [], lp.get("call_to_action") or "Join the waitlist"
    else:
        source = "the founder's brief (no Phase 2 copy yet)"
        headline, sub, bullets, cta = idea or "Coming soon", "", [], "Join the waitlist"
    e = lambda s: html.escape(str(s), quote=True)  # noqa: E731
    page = LANDING_TEMPLATE.format(
        title=e(headline), banner=e(BANNER), headline=e(headline), subheadline=e(sub),
        bullets="\n".join(f"<li>{e(b)}</li>" for b in bullets if str(b).strip()) or "<li>Details coming soon.</li>",
        cta=e(cta), notice=e(DEMO_FORM_NOTICE),
    )
    return page, source


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", str(text).lower()).strip("_")[:30] or "product"


def _plan_inputs(state: dict[str, Any]) -> dict[str, Any]:
    plan = _drafts(state).get("phase3_build_plan") or {}
    riskiest = plan.get("riskiest_assumption") or []
    return {
        "brief": shared.common.brief_for_model(state.get("brief") or {}),
        "mvp_features": plan.get("mvp_features") or [],
        "riskiest_assumption": riskiest[0]["text"] if riskiest and isinstance(riskiest[0], dict) else "",
    }


def _add(total: dict[str, Any], usage: dict[str, Any]) -> dict[str, Any]:
    return {**usage, "tokens": total.get("tokens", 0) + usage.get("tokens", 0),
            "cost": total.get("cost", 0) + usage.get("cost", 0),
            "parsed": total.get("parsed", True) and usage.get("parsed", False),
            "retried": total.get("retried", False) or usage.get("retried", False),
            "rewrote": total.get("rewrote", False) or usage.get("rewrote", False)}


def agent(state: dict[str, Any]) -> dict[str, Any]:
    round_no = int(state.get("round") or 1)
    inputs = _plan_inputs(state)
    usage: dict[str, Any] = {"tokens": 0, "cost": 0, "parsed": True}

    # 1. Format (small call, no file)
    fmt, u = shared.ask(AGENT, FORMAT_SYSTEM, inputs, role="fast", max_tokens=300)
    usage = _add(usage, u)
    kind = fmt.get("format") if fmt.get("format") in ("markdown", "html_tool") else "markdown"
    name = _slug(fmt.get("name") or "guide")
    full_app = bool(fmt.get("full_app_needed"))
    smallest = shared.common.cut(fmt.get("smallest_piece", ""), 240)
    what = shared.common.cut(fmt.get("what", ""), 240)
    spec = {**inputs, "format": kind, "name": name, "what": what, "smallest_piece": smallest if full_app else ""}

    # 2a. Landing page (no model call)
    page, landing_source = landing_html(state)
    files: dict[str, Path] = {"landing": write_output(3, 2, "landing", page, status=STATUS, ext="html")}

    # 2b. Product (one call; an HTML tool that fails to generate falls back to a Markdown guide)
    fallback_note = ""
    product, excerpt, title = "", "", name.replace("_", " ")
    if kind == "html_tool":
        data, _, u = shared.ask_guarded(AGENT, HTML_SYSTEM, spec, round_no, max_tokens=2400)
        usage = _add(usage, u)
        title = shared.common.cut(data.get("title") or title, 100)
        body = str(data.get("body_html") or "")
        if body.strip():
            product = TOOL_TEMPLATE.format(title=html.escape(title), banner=html.escape(BANNER), body=body)
            excerpt = inspect_html(product)[1]
        else:
            kind = "markdown"
            fallback_note = "The model could not produce the HTML tool, so a Markdown guide was built instead."
            spec = {**spec, "format": kind}
    if kind == "markdown":
        data, _, u = shared.ask_guarded(AGENT, MARKDOWN_SYSTEM, spec, round_no, max_tokens=1400)
        usage = _add(usage, u)
        title = shared.common.cut(data.get("title") or title, 100)
        md = str(data.get("markdown") or "").strip()
        md = re.sub(r"^#\s+[^\n]*\n+", "", md).strip()  # the title is added once, below
        product = f"# {title}\n\n{md}\n" if md else ""
        excerpt = md
    ext = "html" if kind == "html_tool" else "md"
    files["product"] = write_output(3, 3, f"product {name}", product, status=STATUS, ext=ext)

    # 2c. User docs (one call), written from the product actually built, not from the plan
    docs_in = {"title": title, "format": kind, "product_excerpt": shared.common.cut(excerpt, 1500),
               "smallest_piece": smallest if full_app else ""}
    d, _, u = shared.ask_guarded(AGENT, DOCS_SYSTEM, docs_in, round_no, max_tokens=700)
    usage = _add(usage, u)
    limits = shared.strings(d.get("limits"), limit=5, chars=200)
    fixed_limits = ["This is a draft generated by an AI agent; the founder reviews and edits it before anyone uses it."]
    if fallback_note:
        fixed_limits.append(fallback_note)
    if full_app:
        fixed_limits.append(f"The idea needs a full app. Only the smallest working piece is built here: {smallest or 'see the build plan'}. "
                            "The full app is not built (STUBBED, on the roadmap).")
    if kind == "html_tool":
        fixed_limits.append("It runs only in the browser: it stores nothing on a server and sends no data.")
    steps = shared.strings(d.get("how_to_use"), limit=6, chars=200)
    docs = (
        f"# {title}: user guide\n\n## What it is\n\n{shared.common.cut(d.get('what_it_is', ''), 400) or what or '_Not stated._'}\n\n"
        "## How to use it\n\n" + ("\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1)) or "_No steps written._") + "\n\n"
        f"## Limits\n\n{shared.bullets(fixed_limits + limits)}\n\n"
        f"## Files\n\n- Product: `{files['product'].name}`\n- Landing page: `{files['landing'].name}` "
        "(its waitlist form is a demo: nothing is sent)\n"
    )
    files["user_docs"] = write_output(3, 4, "user docs", docs, status=STATUS)

    # 3. Checks before Gate 3 (plain Python)
    failures, file_violations = check_build(files)
    for v in file_violations:
        v["agent"] = AGENT
    recommendation = "repeat" if failures else "go"

    log_action(
        agent=AGENT, action="build_product", sources=[], run_id=state.get("run_id"), status=STATUS,
        product_format=kind, full_app_needed=full_app, files=[p.name for p in files.values()],
        checks_failed=failures, recommendation=recommendation, **shared.common.model_fields(usage),
    )
    draft = {
        "format": kind, "name": name, "title": title, "what": what, "full_app_needed": full_app, "smallest_piece": smallest,
        "fallback": fallback_note or None,
        "landing_source": landing_source, "files": {k: str(p) for k, p in files.items()},
        "checks": failures, "recommendation": recommendation, "status": STATUS,
        "reason": "All Gate 3 checks passed." if not failures else "Checks failed: " + "; ".join(failures),
    }
    return {"drafts": {AGENT: draft}, "text_violations": file_violations, "tokens": int(usage.get("tokens", 0))}
